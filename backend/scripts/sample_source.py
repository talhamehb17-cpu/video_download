#!/usr/bin/env python3
"""Run a local "public video source" for development and demos.

It serves synthetic clips (colour bars and a tone generated by FFmpeg) as an HTML
watch page, direct MP4/WebM files, an HLS playlist and a DASH manifest, with
subtitles in several languages. Nothing third-party is involved.

    python scripts/sample_source.py            # serves on http://127.0.0.1:8765

Then start the API with the exemption for exactly this address (development only):

    UNSAFE_ALLOW_HOSTS=127.0.0.1:8765 uvicorn app.main:app --reload

and paste one of the printed links into the app.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import uvicorn  # noqa: E402

from tests.fixtures.build_media import build  # noqa: E402
from tests.fixtures.source_server import create_app  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--dir", type=Path, default=ROOT / ".fixtures", help="where to keep the generated media")
    args = parser.parse_args()

    print("Generating sample media with FFmpeg (first run only)...")
    root = build(args.dir)
    base = f"http://127.0.0.1:{args.port}"
    print(f"\nSample source ready. Start the API with UNSAFE_ALLOW_HOSTS=127.0.0.1:{args.port} and try:\n")
    for label, path in (
        ("Watch page (3 qualities, 3 subtitle languages)", "/watch/demo"),
        ("HLS playlist (adaptive, WebVTT subtitles)", "/hls/master.m3u8"),
        ("DASH manifest (separate video + audio: merged)", "/dash/manifest.mpd"),
        ("WebM page", "/watch/webm"),
        ("Direct file", "/media/v360.mp4"),
        ("Slow file (watch progress, try cancelling)", "/throttled.mp4?delay=0.15"),
        ("Page without a video (error state)", "/article"),
    ):
        print(f"  {label:48} {base}{path}")
    print()
    uvicorn.run(create_app(root), host="127.0.0.1", port=args.port, log_level="warning")


if __name__ == "__main__":
    main()
