async def wait_for_job(
    client: httpx.AsyncClient, job_id: str, *, timeout: float = 60, headers: dict[str, str] | None = None
) -> dict[str, Any]:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        job = (await client.get(f"/api/v1/jobs/{job_id}", headers=headers)).json()
        if job["status"] not in ("queued", "running"):
            return job
        await asyncio.sleep(0.05)
    raise AssertionError(f"job {job_id} did not finish: {job}")


def processes_using(directory: Path) -> list[str]:
    """PIDs of processes whose environment references ``directory`` (a job's worker tree)."""
    needle = str(directory).encode()
    found = []
    for environ in glob.glob("/proc/[0-9]*/environ"):
        try:
            if needle in Path(environ).read_bytes():
                found.append(environ.split("/")[2])
        except OSError:
            continue
    return found
